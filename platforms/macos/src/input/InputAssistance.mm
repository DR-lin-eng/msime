static NSDictionary *MSIMEAssistanceRequest(NSDictionary *request, BOOL dictionary) {
    NSData *bytes=[NSJSONSerialization dataWithJSONObject:request options:0 error:nil];
    if (!bytes || bytes.length>(dictionary ? 2*1024*1024 : 32768)) return nil;
    char *raw=dictionary ? msime_client_dictionary((const uint8_t *)bytes.bytes,bytes.length)
        : msime_client_input_assistance((const uint8_t *)bytes.bytes,bytes.length);
    if (!raw) return nil;
    NSData *response=[NSData dataWithBytes:raw length:strlen(raw)];
    msime_client_string_free(raw);
    NSDictionary *root=[NSJSONSerialization JSONObjectWithData:response options:0 error:nil];
    return [root isKindOfClass:NSDictionary.class] && [root[@"ok"] isEqual:@YES] && [root[@"value"] isKindOfClass:NSDictionary.class] ? root[@"value"] : nil;
}

@implementation MSIMEInputAssistance {
    NSPasteboard *_pasteboard;
    NSDictionary *(^_preferences)(void);
    BOOL (^_isCurrent)(void);
    NSRect (^_caret)(void);
    void (^_insert)(NSString *);
    NSTimer *_timer;
    NSPanel *_panel;
    NSInteger _sequence;
    NSTimeInterval _received;
    NSString *_pendingCode;
}
- (instancetype)initWithPasteboard:(NSPasteboard *)pasteboard preferences:(NSDictionary *(^)(void))preferences
                         isCurrent:(BOOL (^)(void))isCurrent caret:(NSRect (^)(void))caret insert:(void (^)(NSString *))insert {
    if ((self=[super init])) {
        _pasteboard=pasteboard; _preferences=[preferences copy]; _isCurrent=[isCurrent copy];
        _caret=[caret copy]; _insert=[insert copy]; _sequence=pasteboard.changeCount;
    }
    return self;
}
- (NSString *)pendingCode { return _pendingCode; }
- (void)start {
    if (_timer) return;
    __weak MSIMEInputAssistance *weakSelf=self;
    _timer=[NSTimer scheduledTimerWithTimeInterval:0.4 repeats:YES block:^(NSTimer *timer) {
        (void)timer; [weakSelf sampleAtUptime:NSProcessInfo.processInfo.systemUptime];
    }];
}
- (void)clearCode { _pendingCode=nil; [_panel orderOut:nil]; }
- (void)stop { [_timer invalidate]; _timer=nil; [self clearCode]; }
- (void)dealloc { [_timer invalidate]; [_panel orderOut:nil]; }
- (void)sampleAtUptime:(NSTimeInterval)now {
    NSDictionary *preferences=_preferences ? _preferences() : nil;
    BOOL enabled=[preferences[@"clipboard_history"] isEqual:@YES] && ![preferences[@"verification_code_suggestions"] isEqual:@NO];
    if (!enabled || !_isCurrent || !_isCurrent()) {
        _sequence=_pasteboard.changeCount; [self clearCode]; return;
    }
    if (_pendingCode && (now<_received || now>=_received+300)) [self clearCode];
    NSInteger sequence=_pasteboard.changeCount;
    if (sequence==_sequence) return;
    _sequence=sequence;
    [self clearCode];
    // 与既有剪贴板监视器相同，密码管理器和临时内容的标记先于正文读取。
    NSSet *excluded=[NSSet setWithArray:@[@"org.nspasteboard.TransientType",@"org.nspasteboard.ConcealedType",@"org.nspasteboard.AutoGeneratedType",@"de.petermaurer.TransientPasteboardType",@"com.typeit4me.clipping",@"Pasteboard generator type",@"com.agilebits.onepassword"]];
    for (NSPasteboardType type in _pasteboard.types) if ([excluded containsObject:type]) return;
    NSString *text=[_pasteboard stringForType:NSPasteboardTypeString];
    if (!text || text.length>4096 || sequence!=_pasteboard.changeCount) return;
    id code=MSIMEAssistanceRequest(@{@"text":text},NO)[@"code"];
    if (![code isKindOfClass:NSString.class] || !_isCurrent()) return;
    _pendingCode=code; _received=now;
    if (!_panel) {
        _panel=[[NSPanel alloc] initWithContentRect:NSMakeRect(0,0,270,44)
            styleMask:NSWindowStyleMaskBorderless|NSWindowStyleMaskNonactivatingPanel backing:NSBackingStoreBuffered defer:NO];
        _panel.level=NSPopUpMenuWindowLevel; _panel.floatingPanel=YES; _panel.hidesOnDeactivate=NO;
        _panel.becomesKeyOnlyIfNeeded=YES; _panel.hasShadow=YES;
    }
    NSButton *button=[NSButton buttonWithTitle:[@"填入验证码 " stringByAppendingString:code] target:self action:@selector(accept)];
    button.frame=NSMakeRect(4,4,224,36); button.accessibilityIdentifier=@"fillVerificationCode";
    NSButton *close=[NSButton buttonWithTitle:@"×" target:self action:@selector(clearCode)];
    close.frame=NSMakeRect(230,4,36,36); close.accessibilityLabel=@"关闭验证码提示";
    NSView *view=[[NSView alloc] initWithFrame:NSMakeRect(0,0,270,44)];
    [view addSubview:button];[view addSubview:close];_panel.contentView=view;
    NSRect caret=_caret ? _caret() : NSZeroRect;
    if (!NSIsEmptyRect(caret)) [_panel setFrameOrigin:NSMakePoint(NSMinX(caret),NSMinY(caret)-48)];
    else { [self clearCode]; return; }
    [_panel orderFrontRegardless];
}
- (void)accept {
    NSString *code=_pendingCode;
    NSTimeInterval now=NSProcessInfo.processInfo.systemUptime;
    NSDictionary *preferences=_preferences ? _preferences() : nil;
    BOOL live=code && now>=_received && now<_received+300 && _isCurrent && _isCurrent()
        && [preferences[@"clipboard_history"] isEqual:@YES] && ![preferences[@"verification_code_suggestions"] isEqual:@NO];
    [self clearCode];
    if (live && _insert) _insert(code);
}
@end

static NSBackgroundActivityScheduler *MSIMENightActivity;
static NSString *MSIMENightCompletedDay;

void MSIMEStartNightLearning(void) {
    if (MSIMENightActivity) return;
    MSIMENightActivity=[[NSBackgroundActivityScheduler alloc] initWithIdentifier:@"app.msime.macos.night-learning"];
    MSIMENightActivity.interval=3600; MSIMENightActivity.tolerance=600; MSIMENightActivity.repeats=YES;
    MSIMENightActivity.qualityOfService=NSQualityOfServiceUtility;
    [MSIMENightActivity scheduleWithBlock:^(NSBackgroundActivityCompletionHandler completion) {
        @autoreleasepool {
            NSCalendar *calendar=NSCalendar.currentCalendar;
            NSDate *now=NSDate.date;
            NSInteger hour=[calendar component:NSCalendarUnitHour fromDate:now];
            NSString *day=[[calendar startOfDayForDate:now] description];
            CFTypeRef info=IOPSCopyPowerSourcesInfo();
            BOOL charging=info && CFEqual(IOPSGetProvidingPowerSourceType(info),CFSTR(kIOPSACPowerValue));
            if (info) CFRelease(info);
            BOOL idle=CGEventSourceSecondsSinceLastEventType(kCGEventSourceStateCombinedSessionState,kCGAnyInputEventType)>=60;
            if (!charging || !idle || hour>=6 || [day isEqual:MSIMENightCompletedDay] || NSProcessInfo.processInfo.lowPowerModeEnabled) { completion(NSBackgroundActivityResultFinished); return; }
            NSMutableDictionary *options=[MSIMELoadRuntimeOptions() mutableCopy];
            NSString *directory=options[@"preferences_directory"];
            if (![directory isKindOfClass:NSString.class]) { completion(NSBackgroundActivityResultFinished); return; }
            NSData *path=[directory dataUsingEncoding:NSUTF8StringEncoding];
            char *raw=msime_client_load_preferences((const uint8_t *)path.bytes,path.length);
            if (!raw) { completion(NSBackgroundActivityResultFinished); return; }
            NSData *bytes=[NSData dataWithBytes:raw length:strlen(raw)];msime_client_string_free(raw);
            NSDictionary *snapshot=[NSJSONSerialization JSONObjectWithData:bytes options:0 error:nil];
            NSDictionary *preferences=snapshot[@"value"][@"preferences"];
            if (![preferences isKindOfClass:NSDictionary.class]) { completion(NSBackgroundActivityResultFinished); return; }
            options[@"preferences"]=preferences;
            NSDictionary *value=MSIMEAssistanceRequest(@{@"options":options,@"action":@{@"operation":@"night_learning",@"charging":@YES,@"idle":@YES,@"local_hour":@(hour),@"private":@NO}},YES);
            if ([value[@"status"] isEqual:@"trained"]) MSIMENightCompletedDay=day;
            completion(NSBackgroundActivityResultFinished);
        }
    }];
}
void MSIMEStopNightLearning(void) {
    [MSIMENightActivity invalidate]; MSIMENightActivity=nil;
    NSDictionary *options=MSIMELoadRuntimeOptions();
    if (options) (void)MSIMEAssistanceRequest(@{@"options":options,@"action":@{@"operation":@"cancel_night_learning"}},YES);
}
